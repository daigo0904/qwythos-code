// その発言が「作業の依頼」なのか、そうでないのかを、モデルに聞かずに見分ける。
//
// なぜモデルに聞かないか。
// 聞けば1往復ぶん待たされるうえ、指示文や道具の一覧を発言ごとに入れ替えると、
// そのたびに会話を丸ごと読み直すことになる（実測：入れ替えないと 4,923 tok を 0.3 秒、
// 入れ替えると 1,402 tok で 2.0 秒かかった）。判定はここで完結させ、
// 上のほうは一切動かさず、判定結果は発言の末尾に添えるだけにする。
//
// 見分けを外したときの損得が、左右でまったく違う点が設計の軸になる。
//   雑談を「作業」と取り違える → 頼んでいないのにファイルが書き換わる（実害あり）
//   作業を「雑談」と取り違える → 手を出す前に一度確認が出るだけ（y を押せば進む）
// なので、はっきり作業だと分かるものだけを作業とし、迷ったら雑談側に置く。

// 依頼の言い方。これがあれば作業とみなす。
// 「〜して」「〜してくれ」だけでなく、動詞のて形（合わせて・置き換えて）も拾う。
// 日本語の依頼はほぼここに集まるので、ここが緩いと作業が雑談に落ちる。
const REQUEST = new RegExp(
  [
    // て形＋依頼の助動詞。「揃えてくれる？」「直してもらえる？」「見てほしい」。
    // 「して〜」に限らないのが肝心で、限ると「合わせてくれる？」を取りこぼす。
    '[ぁ-んァ-ヶー一-龠][てで](?:くれ|もら|いただ|ください|下さい|ほし|欲し|ちょうだい)',
    // 句の終わりに来た動詞のて形（〜して。／〜合わせて／〜直して、）。
    //
    // 促音のあとの「て」だけは外す。「そうなんだって」「明日休みだって」は
    // 伝聞であって依頼ではなく、ここを通すと雑談が作業と判定されてしまう。
    // 巻き添えで「やって」「送って」まで落ちるので、よく使うものは下に名前で挙げる。
    // 依頼を取りこぼしても確認が1回出るだけだが、逆はファイルが書き換わる。
    '[ぁ-んァ-ヶー一-龠](?<!っ)[てで](?:ね|よ|な)?[。、！？!?]?$',
    // 「て」の直後が「いる・る・ます」なら、頼んでいるのではなく説明している。
    // 「これやって」は依頼だが、「なにやってるの？」は質問である。
    '(?:やっ|作っ|使っ|送っ|取っ|貼っ|打っ|切っ|入れ|戻し|直し)て(?![いるらまき])',
    // 作業を指す動詞。活用の頭だけを見る
    '(?:直|なお|治)(?:し|す|せ|そ)',
    '(?:修正|変更|追加|削除|実装|作成|置換|置き換え|書き換え|リネーム|リファクタ)',
    '(?:作|創|つく)(?:っ|り|る|れ|ろ)',
    '(?:足|加)(?:し|す|え|える)',
    '(?:消|け)(?:し|す|せ)',
    '(?:書|か)(?:い|く|け)(?:て|と)',
    '(?:動かし|走らせ|実行し|試し|確かめ)',
    '(?:コミット|プッシュ|マージ|デプロイ|インストール)',
    '(?:整理|掃除|きれいに|片付け)',
    '(?:対応|着手|やっと)いて',
    // **命令形と終止形も依頼である。**「〜してください」の形しか受けていなかったので、
    //   「再試行の回数を2倍に増やす」「ログを最後の5行に切り詰めなさい。」
    // が雑談と判定され、**見張りが丸ごと無効になっていた**（2026-09-24 実測で2件）。
    // 雑談扱いは `shouldNudgeToAct()` を false にするので、
    // 嘘の報告に誰も気づけなくなる。**取りこぼしの害がいちばん大きい場所。**
    '(?:なさい|しろ|せよ|してくれ)[。、！？!?]?$',
    // 和語の動詞。「増やす」「減らす」「切り詰める」など、
    // サ変（修正・変更…）の一覧では受けられないもの。
    '(?:増|ふ|減|へ|伸|の|縮|ちぢ|広|ひろ|狭|せば)(?:やし|やす|やせ|らし|らす|らせ|ばし|ばす|め|めて|める|げ|げる)',
    '(?:切り詰め|打ち切|絞|しぼ|揃|そろ|並べ替え|入れ替え|置き直)(?:り|る|れ|え|える|めて|め)',
    '(?:上げ|下げ|付け|外し|外す|外せ|寄せ|回し|止め|抜い|抜く)(?:る|て|た)?[。、！？!?]?$',
    // **サ変名詞＋「行う」。**依頼の言い方として非常に多い形なのに落ちていた。
    //   「ログの切り詰めを行う」「設定の見直しを行ってください」
    // 実測（2026-09-24）で、これも雑談と判定され見張りが丸ごと無効になっていた。
    // **「流行った」に当たらないよう、直前を縛る。**
    //   `行(?:う|い|って)` だけにしたら「TypeScript ってなんで**流行った**んだろう」
    //   「最近ローカルLLM**流行って**るよね」を依頼と読んだ（2026-09-24）。
    //   「〜を行う」「〜の実施を行って」の形に限る。
    '(?:を|の)行(?:う|い|って|った|いたい|ってくれ)',
    // 名詞だけで頼む形。「〜の修正」「〜の削除」など、動詞を伴わない依頼
    '(?:の|を)(?:修正|変更|削除|追加|作成|更新|置換|書き換え|切り詰め|整理|統合|分割)(?:を|$|[。、！？!?])'
  ].join('|'),
  'm'
);

// 英語で言われたときの命令形。文の頭にあるものだけを見る。
const REQUEST_EN =
  /^\s*(?:please\s+)?(?:fix|add|create|write|implement|refactor|remove|delete|drop|run|build|test|update|change|modify|make|rename|move|install|commit|push|merge|revert|clean)\b/i;

// ファイルやパスの名指し。名前を出してくるのは、たいてい何かしてほしいとき。
const FILE_REF =
  /(?:^|[\s「『（(])[\w./~-]*\.(?:js|mjs|cjs|ts|tsx|jsx|py|rs|go|java|rb|php|sh|zsh|json|md|ya?ml|toml|css|scss|html|sql|txt)\b|@[\w./-]+/;

// 作業そのものを指す名詞。体言止めの依頼（「ログイン機能の追加」）を拾う。
const WORK_NOUN = /(?:追加|修正|削除|実装|作成|変更|対応|置換|整理|移行|リファクタ|バグ|エラー|不具合|テスト|ビルド|デプロイ)/;

// 質問の終わり方。答えれば済むもので、書き換える必要はない。
const QUESTION = /[？?]\s*$/m;
const QUESTION_WORD = /(?:どう思|どっち|どちら|なんで|なぜ|どうして|って何|とは何|ってなに|かな[あぁ]?$|だろう|でしょうか)/m;

// 雑談の言い回し。感想・相づち・独り言。
const CHATTY =
  /(?:こんにち|こんばん|おはよ|おやすみ|お疲れ|おつかれ|ありがと|さんきゅ|よろしく|すご[いく]|なるほど|たしかに|確かに|そうだね|だよね|ですね|だなあ|だな[。！!]?$|ですよ|かもね|らしいね|みたいだね|と思う|気がする|そういえば|ところで|ちなみに)/m;

// 一語の同意。「うん」「はい」「y」だけの返事。
//
// **打ち消しは入れない。**「ううん」「いや」は同意ではないので、
// ここに混ぜると断ったつもりの返事で作業が始まる。
const AFFIRM =
  /^(?:うん|はい|ええ|そう|そうそう|そうだね|それで|それでいい|いいよ|いいね|おｋ|おk|ok|okay|yes|yeah|yep|y|ｙ|うい|了解|わかった|分かった|よろしく)[。、.!！\s]*$/i;

/**
 * その発言を、作業の依頼として受け取ってよいかを見る。
 *
 * @param {string} text 利用者の発言
 * @param {{ replyingTo?: boolean }} [opts]
 *   replyingTo … 直前にこちらが何か言っている（＝この発言は返事）かどうか。
 *
 * @returns {{ smallTalk: boolean, reason: string }}
 *   smallTalk が true なら「書き換えないで答える」側。
 */
export function classifyInput(text, opts = {}) {
  const t = String(text ?? '').trim();
  if (!t) return { smallTalk: false, reason: '' };

  // 「うん」だけの返事は、**直前に出した提案への同意**であることが多い。
  //
  // ここを雑談に落とすと、「ファイルは変更しないこと」と言い添えたうえで、
  // 書き換えようとした瞬間に確認を出すことになる。**同意した直後にもう一度聞く**形で、
  // 実機の記録では41件中6回これが起きていた。
  //
  // 判定は今の発言しか見ないので、「うん」単体からは何への同意か分からない。
  // 分からないまま雑談に倒すより、直前にこちらが話していたなら**その続き**として扱う。
  // 会話の最初の「うん」は、返事する相手がいないので今までどおり雑談側に置く。
  if (opts.replyingTo && AFFIRM.test(t)) return { smallTalk: false, reason: '直前の話への返事' };

  // 貼り付けられたコードやエラーは、見てほしいから貼っている。
  // 短い独り言と違って、ここを雑談に落とすと毎回よけいな確認が出る。
  if (/```/.test(t) || t.split('\n').length > 5) {
    return { smallTalk: false, reason: '貼り付け' };
  }

  // 依頼の言い方が先。「長いよね。短くして」のように、
  // 雑談の言い回しと同じ文に入っていても、頼まれているほうが勝つ。
  if (REQUEST.test(t) || REQUEST_EN.test(t)) return { smallTalk: false, reason: '依頼の言い方' };

  // 疑問形で、依頼の言い方が無いもの。
  // 答えるだけで済むし、読む道具は雑談側でも使えるので、調べて答えることはできる。
  if (QUESTION.test(t) || QUESTION_WORD.test(t)) return { smallTalk: true, reason: '質問' };

  // 雑談の言い回しは、ファイル名より先に見る。
  //
  // 「tax.js の税率、古いままだなあ」を実際に試したら、ファイル名のほうが勝って
  // 黙って書き換わった。名前を出しているだけで頼んではいないので、ここは独り言が勝つ。
  if (CHATTY.test(t)) return { smallTalk: true, reason: '雑談の言い方' };

  // 体言止めの依頼（「ログイン機能の追加」「テストの修正」）。
  if (WORK_NOUN.test(t)) return { smallTalk: false, reason: '作業の名指し' };

  // ファイルやパスを名指ししている。頼み方はしていないが、用があるから名前を出している。
  if (FILE_REF.test(t)) return { smallTalk: false, reason: 'ファイルの名指し' };

  // どれにも当てはまらないもの（「うーん」「疲れた」）。
  // 迷ったら雑談側。書き換えたくなったら、そのとき確認が出る。
  return { smallTalk: true, reason: '依頼の形になっていない' };
}

// 雑談と見たとき、その発言の末尾に添える一言。
//
// **末尾に置くのが肝心**で、いちばん上の指示文を書き換えてはいけない。
// 上を触ると会話を丸ごと読み直すことになり、返事が目に見えて遅くなる。
// 道具を取り上げないのもわざと。本当に必要ならモデルには呼ばせて、
// 呼んだ瞬間に人へ確認を出すほうが、判定を外したときの取り返しがきく。
// 添えた一言を、人に見せる文から外す。
//
// 添える先が利用者の発言そのものなので、そのまま出すと
// 会話の一覧に判定の説明文が並んでしまう（実際にそうなった）。
// モデルには渡したままにしたいので、消すのではなく表示のときだけ落とす。
export function withoutHint(text) {
  let s = String(text ?? '');
  // 末尾に添えたものは、モデルには渡したままで、人に見せる文からは落とす。
  // 会話の一覧に判定や事実確認の文が並んでしまうため（実際にそうなった）。
  for (const mark of ['\n\n[自動判定：', '\n\n[事実確認：']) {
    const at = s.indexOf(mark);
    if (at !== -1) s = s.slice(0, at);
  }
  return s;
}

